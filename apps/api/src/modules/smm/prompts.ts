/** Строка о дне выхода, чтобы модель держала в голове контекст времени. */
export function whenLine(publishAt: string | null): string {
  if (!publishAt) return 'Дата выхода не назначена.'
  const d = new Date(publishAt)
  const msk = new Date(d.getTime() + 3 * 3600_000)
  return `Выходит ${msk.toISOString().slice(0, 10)} (${WEEKDAYS[msk.getUTCDay()]}) в ${msk.toISOString().slice(11, 16)} МСК.`
}
