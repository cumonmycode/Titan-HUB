-- 079: заявки с сайта клуба (titanmafia.ru) живут в bookings рядом с бронями виджета.
--
-- kind — что за заявка и что значит «Подтвердить» в HUB:
--   event   — мероприятие (ДР, корпоратив, детская, сертификат…): подтверждение
--             создаёт planned-мероприятие, как у брони виджета /book (дефолт);
--   game    — запись на игровой вечер: подтверждение = «ждём гостя», без мероприятия;
--   message — обращение (сотрудничество, вопрос): подтверждение = «обработано».
-- meta — структурированные поля формы (формат, вечер, Telegram, № сертификата,
-- страница-источник). Человекочитаемая сводка дублируется в comment, чтобы
-- старые сборки приложения HUB показывали заявку целиком. Аддитивно, на всех БД.
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS kind text NOT NULL DEFAULT 'event';
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS meta jsonb;
